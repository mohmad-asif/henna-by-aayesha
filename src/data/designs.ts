export function getFeaturedDesigns(): MehndiDesign[] {
  return mehndiDesigns.filter((d) => d.featured);
}

export function getDesignBySlug(slug: string): MehndiDesign | undefined {
  return mehndiDesigns.find((d) => d.slug === slug);
}

export function getRelatedDesigns(currentSlug: string, limit = 3): MehndiDesign[] {
  return mehndiDesigns.filter((d) => d.slug !== currentSlug).slice(0, limit);
}
